#!/usr/bin/env python3
"""Generate per-LUT example photos for the LUT selector.

Every bundled LUT gets example images under assets/luts/examples/<lutId>/ so
the selector can show real reference colors. LUTs with hand-picked originals
(the EXCEPTIONS map: lutId -> list of source photos) use those; all others get
one example generated by applying their .plut (PLUT v1, size 33, uint16,
b->g->r node order, r fastest) to the shared reference photo with trilinear
interpolation. Log-restore LUTs are skipped: they are technical transforms
for log footage, a graded sRGB example would misrepresent them.
"""
import json, os, struct, sys
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LUTS_DIR = os.path.join(ROOT, "app/src/main/assets/luts")
OUT_ROOT = os.path.join(LUTS_DIR, "examples")
REFERENCE = os.path.expanduser("~/workspace/amelia-samples/amelia_2.jpg")
EXCEPTIONS = {
    "amelia": [os.path.expanduser(f"~/workspace/amelia-samples/amelia_{i}.jpg") for i in range(1, 7)],
    "tomosaki": [os.path.expanduser(f"~/workspace/tomosaki-samples/p{i}.jpg") for i in range(1, 9)],
}
SKIP_CATEGORIES = {"Log"}
MAX_W = 560


def load_plut(path):
    raw = open(path, "rb").read()
    magic, _ver, size, dtype = struct.unpack("<4i", raw[:16])
    assert magic == 0x54554C50, path
    if dtype == 1:  # UINT16
        data = np.frombuffer(raw[16:], dtype="<u2").astype(np.float32) / 65535.0
    else:  # UINT8
        data = np.frombuffer(raw[16:], dtype=np.uint8).astype(np.float32) / 255.0
    return data.reshape(size, size, size, 3), size  # axes: b, g, r


def apply_lut(img, grid, size):
    """img: float32 HxWx3 in 0..1. Trilinear sample of the b,g,r grid."""
    x = np.clip(img, 0.0, 1.0) * (size - 1)
    lo = np.floor(x).astype(np.int32)
    hi = np.minimum(lo + 1, size - 1)
    frac = x - lo
    r, g, b = img[..., 0], img[..., 1], img[..., 2]
    rl, gl, bl = lo[..., 0], lo[..., 1], lo[..., 2]
    rh, gh, bh = hi[..., 0], hi[..., 1], hi[..., 2]
    fr, fg, fb = frac[..., 0][..., None], frac[..., 1][..., None], frac[..., 2][..., None]
    c000 = grid[bl, gl, rl]; c001 = grid[bl, gl, rh]
    c010 = grid[bl, gh, rl]; c011 = grid[bl, gh, rh]
    c100 = grid[bh, gl, rl]; c101 = grid[bh, gl, rh]
    c110 = grid[bh, gh, rl]; c111 = grid[bh, gh, rh]
    c00 = c000 * (1 - fr) + c001 * fr
    c01 = c010 * (1 - fr) + c011 * fr
    c10 = c100 * (1 - fr) + c101 * fr
    c11 = c110 * (1 - fr) + c111 * fr
    c0 = c00 * (1 - fg) + c01 * fg
    c1 = c10 * (1 - fg) + c11 * fg
    return c0 * (1 - fb) + c1 * fb


def save_example(src_img, out_path):
    im = src_img.copy()
    if im.width > MAX_W:
        im = im.resize((MAX_W, int(im.height * MAX_W / im.width)), Image.LANCZOS)
    im.save(out_path, quality=78)
    return os.path.getsize(out_path)


def main():
    config = json.load(open(os.path.join(LUTS_DIR, "config.json")))
    reference = Image.open(REFERENCE).convert("RGB")
    ref_arr = np.asarray(reference, dtype=np.float32) / 255.0
    total = 0
    for entry in config["luts"]:
        lut_id, path = entry["id"], entry.get("path", "")
        if not path or entry.get("category", "") in SKIP_CATEGORIES:
            continue
        out_dir = os.path.join(OUT_ROOT, lut_id)
        os.makedirs(out_dir, exist_ok=True)
        if lut_id in EXCEPTIONS:
            sizes = []
            for i, src in enumerate(EXCEPTIONS[lut_id], 1):
                sizes.append(save_example(Image.open(src).convert("RGB"), os.path.join(out_dir, f"{i}.jpg")))
            print(f"{lut_id}: {len(sizes)} originals, {sum(sizes)//1024} KB")
        else:
            grid, size = load_plut(os.path.join(LUTS_DIR, path))
            graded = apply_lut(ref_arr, grid, size)
            out = Image.fromarray(np.round(np.clip(graded, 0, 1) * 255).astype(np.uint8))
            kb = save_example(out, os.path.join(out_dir, "1.jpg")) // 1024
            print(f"{lut_id}: generated, {kb} KB")
        total += 1
    print("LUTs with examples:", total)


if __name__ == "__main__":
    sys.exit(main())
